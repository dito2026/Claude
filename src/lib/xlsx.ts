/**
 * Entrega un archivo al usuario. En celular (sobre todo iPhone con la app instalada) la descarga directa
 * no funciona: se usa «Compartir» (guardar en Archivos, enviar por WhatsApp…). En computador, descarga normal.
 */
export async function saveFile(name: string, data: Uint8Array | string, mime: string) {
  const blob = new Blob([data as BlobPart], { type: mime });
  const file = typeof File !== 'undefined' ? new File([blob], name, { type: mime }) : null;
  const touch = typeof matchMedia !== 'undefined' && matchMedia('(pointer: coarse)').matches;
  if (touch && file && typeof navigator !== 'undefined' && navigator.canShare?.({ files: [file] })) {
    try {
      await navigator.share({ files: [file], title: name });
      return;
    } catch (e) {
      if ((e as Error)?.name === 'AbortError') return;
    }
  }
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  a.rel = 'noopener';
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 10000);
}
